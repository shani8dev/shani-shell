#!/usr/bin/env python3
"""make-world-map — rebuild shani/Common/world-land.js from Natural Earth's land.

The first-boot wizard draws a clickable world map on its time-zone step. The
shapes come from Natural Earth 1:110m land (public domain, naturalearthdata.com),
which is coarse enough to read as a map and small enough to ship in the repo.

    curl -L -o /tmp/ne_110m_land.geojson \
        https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
    tools/make-world-map.py /tmp/ne_110m_land.geojson

Points are rounded to 0.02 degrees (~2 km at the equator): at the map's 540 px
width one pixel is ~0.67 degrees, so nothing is lost, and the file stays small.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
# the setup wizard and the shell's Settings each carry their own copy (their
# configs are installed separately and share no import path), so the one
# generated file is written to both
# one copy: setup/ and greeter/ reach shani/Common through their Common symlink
OUTS = [os.path.join(ROOT, "shani", "Common", "world-land.js")]
STEP = 0.02


def ring_points(ring):
    # a closed ring repeats its first point; the canvas closes it itself
    if len(ring) > 1 and ring[0] == ring[-1]:
        ring = ring[:-1]
    pts = []
    for lon, lat in ring:
        p = [round(round(lon / STEP) * STEP, 2), round(round(lat / STEP) * STEP, 2)]
        if not pts or pts[-1] != p:
            pts.append(p)
    return pts


def main(argv):
    if len(argv) < 2:
        sys.exit(__doc__)
    data = json.load(open(argv[1]))
    rings = []
    for feature in data["features"]:
        geom = feature["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        for poly in polys:
            for ring in poly:
                pts = ring_points(ring)
                if len(pts) >= 4:
                    rings.append(pts)
    body = ",\n".join(
        "[" + ",".join(f"[{x:g},{y:g}]" for x, y in ring) + "]" for ring in rings
    )
    text = (
        ".pragma library\n"
        "// Land outlines for the time-zone map (setup and Settings). Generated by\n"
        "// tools/make-world-map.py from Natural Earth 1:110m land (public domain);\n"
        "// do not edit. Each ring is a list of [longitude, latitude] pairs in\n"
        "// degrees, rounded to 0.02.\n"
        "var rings = [\n" + body + "\n];\n"
    )
    for out in OUTS:
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w") as f:
            f.write(text)
        print(f"{out}: {len(rings)} rings, {os.path.getsize(out) // 1024} KiB")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
